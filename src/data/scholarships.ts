/**
 * Computes an ISO date string offset by a designated number of days
 * relative to the runtime moment, guaranteeing the hackathon demo
 * always displays active, realistic, and unexpired countdowns.
 */
export const getRelativeDeadlineDate = (days: number): string => {
  const target = new Date();
  target.setDate(target.getDate() + days);
  target.setHours(23, 59, 59, 999);
  return target.toISOString();
};

